/// Набор эмодзи по разделам — в том порядке, что и в системной палитре.
///
/// Полного списка Unicode тут нет нарочно: больше тысячи вариантов профессий
/// и цветов кожи делают сетку бесконечной, а ищут почти всегда одно и то
/// же. Английские названия берутся у самой системы (`CFStringTransform`),
/// флаги называются через `Locale`, а русские слова — короткий словарь
/// ниже, только для ходовых.
enum EmojiCategory: String, CaseIterable, Identifiable, Sendable {
    case smileys, people, nature, food, activity, travel, objects, symbols, flags

    var id: String { rawValue }

    var symbol: String {
        switch self {
        case .smileys: return "face.smiling"
        case .people: return "hand.raised"
        case .nature: return "leaf"
        case .food: return "fork.knife"
        case .activity: return "soccerball"
        case .travel: return "car"
        case .objects: return "lightbulb"
        case .symbols: return "heart"
        case .flags: return "flag"
        }
    }

    var titleKey: L10n.Key {
        switch self {
        case .smileys: return .emojiSmileys
        case .people: return .emojiPeople
        case .nature: return .emojiNature
        case .food: return .emojiFood
        case .activity: return .emojiActivity
        case .travel: return .emojiTravel
        case .objects: return .emojiObjects
        case .symbols: return .emojiSymbols
        case .flags: return .emojiFlags
        }
    }

    var emoji: [String] {
        if self == .flags {
            return EmojiData.regions.map(EmojiData.flag(for:))
        }
        return (EmojiData.table[self] ?? "").split(separator: " ").map(String.init)
    }
}

