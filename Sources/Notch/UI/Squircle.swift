import SwiftUI

/// Суперэллипс вместо круга: форма подсветки под значками.
///
/// Круг под квадратным значком — форма чужая: у значков в панели углы
/// скруглённые, и круглая подложка спорит с ними, а не повторяет их.
/// Суперэллипс — то же скругление, каким система рисует иконки: кривизна
/// не обрывается на границе дуги и прямой, а нарастает, поэтому переход
/// не читается стыком.
///
/// Точного суперэллипса SwiftUI не даёт, но `.continuous` у скруглённого
/// прямоугольника — это он и есть: Apple рисует им иконки и виджеты.
/// Радиус берём долей от меньшей стороны, чтобы одна и та же форма шла и
/// на кнопку транспорта в полсотни точек, и на крестик в шестнадцать.
struct Squircle: Shape {
    /// Доля меньшей стороны, уходящая в скругление.
    ///
    /// Половина дала бы обратно круг, четверть — кнопку с углами. Сорок
    /// сотых оставляют форму круглой на глаз и при этом заметно не
    /// круглой: у значка появляются бока, которых у круга нет.
    static let ratio: CGFloat = 0.4

    var inset: CGFloat = 0

    func path(in rect: CGRect) -> Path {
        let box = rect.insetBy(dx: inset, dy: inset)
        let radius = min(box.width, box.height) * Self.ratio
        return RoundedRectangle(cornerRadius: radius, style: .continuous).path(in: box)
    }
}

extension Squircle: InsettableShape {
    func inset(by amount: CGFloat) -> Squircle {
        Squircle(inset: inset + amount)
    }
}
