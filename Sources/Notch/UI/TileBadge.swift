import SwiftUI

/// Ярлык в углу плитки: коротко, что это за запись.
///
/// Кадр занимает всю плитку, подписи под ним нет — иначе превью ужимается
/// вдвое и скриншот в нём снова не разглядеть. Но плитка без единого слова
/// превращается в ребус, поэтому тип записи остаётся капсулой поверх кадра.
struct TileBadge: View {
    let text: String

    var body: some View {
        Text(text)
            .font(.system(size: 9, weight: .medium))
            .foregroundStyle(NotchTheme.textSecondary)
            .lineLimit(1)
            // Строка центруется по своей коробке, а не по буквам: снизу в ней
            // место под хвосты (g, p, y), сверху — нет. От этого слово сидело
            // ниже середины капсулы. Поднимаем его на половину этого запаса.
            .offset(y: -0.5)
            .padding(.horizontal, 5)
            .frame(height: 13)
            .background {
                Capsule()
                    // Своя подложка, а не общий `accentSelection`: капсула
                    // лежит на кадре, и просвечивать он не должен.
                    .fill(NotchTheme.background.opacity(0.72))
            }
            // Плитка сама отбита от края на 3 — ярлык отбиваем ещё на 3,
            // чтобы он не лип к кадру.
            .padding(6)
    }
}
